    d4.evaluate("window.__popupErr=null")
    d4.evaluate("window.__popupErr='auth/popup-closed-by-user'"); d4.click('#lgGoogle') if d4.evaluate("document.getElementById('lgGoogle').offsetParent!==null") else None
